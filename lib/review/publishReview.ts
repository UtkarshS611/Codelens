import mongoose from "mongoose";

import { githubApp } from "@/lib/github/app";
import { Review } from "@/lib/db/models/Review";

import type {
    ReviewContext,
    ReviewResult,
    ReviewFinding,
} from "@/lib/review/types";

interface PublishReviewParams {
    installationId: number;
    context: ReviewContext;
    result: ReviewResult;
    reviewId: string | mongoose.Types.ObjectId;
}

interface GitHubInlineComment {
    path: string;
    body: string;
    line: number;
    side: "RIGHT";
    start_line?: number;
    start_side?: "RIGHT";
}

interface PreparedInlineComment {
    findingIndex: number;
    path: string;
    body: string;
    line: number;
    side: "RIGHT";
    start_line?: number;
    start_side?: "RIGHT";
}

interface DiffLineInfo {
    addedLines: Set<number>;
    lineHunks: Map<number, number>;
}

export interface PublishReviewResult {
    githubReviewId: number;
    githubReviewUrl: string;
    inlineCommentsSaved: number;
    findingsWithoutInlineComments: number;
    reusedExistingReview: boolean;
}

// -----------------------------------------------------------------------------
// Diff parsing
// -----------------------------------------------------------------------------

/**
 * Extract added lines and line-to-hunk mappings from a unified diff patch.
 *
 * GitHub inline comments must refer to valid lines in the PR diff.
 * We only publish inline comments whose ending line is an added line.
 */
function parseDiffLines(patch: string | null): DiffLineInfo {
    const addedLines = new Set<number>();
    const lineHunks = new Map<number, number>();

    if (!patch) {
        return { addedLines, lineHunks };
    }

    let currentNewLine: number | null = null;
    let hunkIndex = -1;

    for (const line of patch.split(/\r?\n/)) {
        const hunkHeader = line.match(
            /^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@/,
        );

        if (hunkHeader) {
            currentNewLine = Number(hunkHeader[1]);
            hunkIndex += 1;
            continue;
        }

        if (currentNewLine === null) {
            continue;
        }

        // Metadata lines do not represent source lines.
        if (line.startsWith("\\")) {
            continue;
        }

        // Added line: advances the new-file line counter.
        if (line.startsWith("+") && !line.startsWith("+++")) {
            addedLines.add(currentNewLine);
            lineHunks.set(currentNewLine, hunkIndex);
            currentNewLine += 1;
            continue;
        }

        // Removed line: does not advance the new-file line counter.
        if (line.startsWith("-") && !line.startsWith("---")) {
            continue;
        }

        // Context line: exists in the new file but wasn't added.
        if (line.startsWith(" ")) {
            lineHunks.set(currentNewLine, hunkIndex);
            currentNewLine += 1;
        }
    }

    return { addedLines, lineHunks };
}

// -----------------------------------------------------------------------------
// Comment formatting
// -----------------------------------------------------------------------------

function formatInlineComment(finding: ReviewFinding): string {
    const parts = [
        `**[${finding.severity.toUpperCase()}] ${finding.title}**`,
        finding.description,
    ];

    if (finding.suggestion) {
        parts.push(`**Suggested fix:** ${finding.suggestion}`);
    }

    return parts.join("\n\n");
}

function formatUnanchoredFinding(
    finding: ReviewFinding,
): string {
    const line =
        finding.startLine !== null
            ? ` (line ${finding.startLine}${finding.endLine !== null &&
                finding.endLine !== finding.startLine
                ? `–${finding.endLine}`
                : ""
            })`
            : "";

    const parts = [
        `### [${finding.severity.toUpperCase()}] ${finding.title}`,
        `**File:** \`${finding.file}\`${line}`,
        finding.description,
    ];

    if (finding.suggestion) {
        parts.push(`**Suggested fix:** ${finding.suggestion}`);
    }

    return parts.join("\n\n");
}

function buildReviewBody(
    result: ReviewResult,
    unanchoredFindings: ReviewFinding[],
    marker: string,
): string {
    const parts = [
        "## CodeLens AI Review",
        result.summary,
    ];

    if (unanchoredFindings.length > 0) {
        parts.push(
            "## Findings without inline comments",
            "The following findings could not safely be attached to an added line in the PR diff.",
            ...unanchoredFindings.map(formatUnanchoredFinding),
        );
    }

    parts.push(
        "---",
        "_Generated by CodeLens using a local AI model._",
        marker,
    );

    return parts.join("\n\n");
}

// -----------------------------------------------------------------------------
// Main publisher
// -----------------------------------------------------------------------------

export async function publishReview({
    installationId,
    context,
    result,
    reviewId,
}: PublishReviewParams): Promise<PublishReviewResult> {
    const mongoReviewId = new mongoose.Types.ObjectId(
        reviewId.toString(),
    );

    const { repository, pullRequest } = context;
    const { owner, name: repo } = repository;
    const pull_number = pullRequest.number;

    const logPrefix =
        `[CodeLens Publish] ${repository.fullName}#${pull_number}`;

    const marker =
        `<!-- codelens-review:${mongoReviewId.toString()} -->`;

    console.info(`${logPrefix} Starting publication`, {
        installationId,
        reviewId: mongoReviewId.toString(),
        findingCount: result.findings.length,
    });

    const dbReview = await Review.findById(mongoReviewId);

    if (!dbReview) {
        throw new Error(
            `MongoDB review ${mongoReviewId.toString()} was not found.`,
        );
    }

    const octokit =
        await githubApp.getInstallationOctokit(installationId);

    // Build the set of findings that can safely be inline comments.
    const inlineComments: PreparedInlineComment[] = [];
    const inlineFindingIndexes = new Set<number>();

    const diffInfoByPath = new Map<string, DiffLineInfo>();

    for (const file of context.files) {
        diffInfoByPath.set(file.path, parseDiffLines(file.patch));
    }

    for (const [findingIndex, finding] of result.findings.entries()) {
        const diffInfo = diffInfoByPath.get(finding.file);

        if (!diffInfo) {
            console.warn(`${logPrefix} File is not in review context`, {
                findingIndex,
                file: finding.file,
            });
            continue;
        }

        const startLine = finding.startLine;
        const endLine = finding.endLine;

        const commentLine = endLine ?? startLine;

        if (commentLine === null) {
            console.warn(`${logPrefix} Finding has no usable line`, {
                findingIndex,
                file: finding.file,
            });
            continue;
        }

        // Require the ending line to be an actual added line.
        if (!diffInfo.addedLines.has(commentLine)) {
            console.warn(`${logPrefix} Finding is not on an added line`, {
                findingIndex,
                file: finding.file,
                startLine,
                endLine,
            });
            continue;
        }

        // GitHub requires a multi-line review comment to stay within
        // one diff hunk, with valid start and ending lines.
        const isMultiLine =
            startLine !== null &&
            endLine !== null &&
            startLine !== endLine;

        if (isMultiLine) {
            const startHunk = diffInfo.lineHunks.get(startLine);
            const endHunk = diffInfo.lineHunks.get(endLine);

            if (
                startLine > endLine ||
                startHunk === undefined ||
                endHunk === undefined ||
                startHunk !== endHunk
            ) {
                console.warn(`${logPrefix} Invalid inline line range`, {
                    findingIndex,
                    file: finding.file,
                    startLine,
                    endLine,
                });
                continue;
            }
        }

        const comment: PreparedInlineComment = {
            findingIndex,
            path: finding.file,
            body: formatInlineComment(finding),
            line: commentLine,
            side: "RIGHT",
        };

        if (isMultiLine && startLine !== null) {
            comment.start_line = startLine;
            comment.start_side = "RIGHT";
        }

        inlineComments.push(comment);
        inlineFindingIndexes.add(findingIndex);
    }

    const unanchoredFindings = result.findings.filter(
        (_, index) => !inlineFindingIndexes.has(index),
    );

    const reviewBody = buildReviewBody(
        result,
        unanchoredFindings,
        marker,
    );

    console.info(`${logPrefix} Prepared GitHub review`, {
        inlineCommentCount: inlineComments.length,
        unanchoredFindingCount: unanchoredFindings.length,
    });

    // ---------------------------------------------------------------------------
    // Idempotency
    //
    // Prefer the saved review ID. If MongoDB wasn't updated after a previous
    // successful GitHub request, search for our marker before creating another.
    // ---------------------------------------------------------------------------

    let githubReviewId = dbReview.githubReviewId;
    let githubReviewUrl = dbReview.githubReviewUrl;
    let reusedExistingReview = Boolean(githubReviewId);

    if (!githubReviewId) {
        const existingGitHubReviews = await octokit.paginate(
            octokit.rest.pulls.listReviews,
            {
                owner,
                repo,
                pull_number,
                per_page: 100,
            },
        );

        const matchingReview = existingGitHubReviews.find(
            (review) => review.body?.includes(marker),
        );

        if (matchingReview) {
            githubReviewId = matchingReview.id;
            githubReviewUrl = matchingReview.html_url;
            reusedExistingReview = true;

            console.info(`${logPrefix} Found existing GitHub review`, {
                githubReviewId,
            });
        }
    }

    // ---------------------------------------------------------------------------
    // Create the GitHub review if it doesn't exist.
    // ---------------------------------------------------------------------------

    if (!githubReviewId) {
        const comments: GitHubInlineComment[] = inlineComments.map(
            ({
                findingIndex: _findingIndex,
                ...comment
            }) => comment,
        );

        console.info(`${logPrefix} Creating GitHub review`, {
            inlineCommentCount: comments.length,
        });

        const response = await octokit.rest.pulls.createReview({
            owner,
            repo,
            pull_number,
            body: reviewBody,
            event: "COMMENT",
            comments,
        });

        githubReviewId = response.data.id;
        githubReviewUrl = response.data.html_url;

        console.info(`${logPrefix} GitHub review created`, {
            githubReviewId,
            githubReviewUrl,
            state: response.data.state,
        });
    }

    // Persist the review ID immediately so retries can reuse the review
    // rather than posting a duplicate.
    const savedReview = await Review.findByIdAndUpdate(
        mongoReviewId,
        {
            $set: {
                githubReviewId,
                ...(githubReviewUrl ? { githubReviewUrl } : {}),
            },
        },
        {
            returnDocument: "after",
        },
    );

    if (!savedReview) {
        throw new Error(
            `Could not save GitHub review ID for ${mongoReviewId.toString()}.`,
        );
    }

    // ---------------------------------------------------------------------------
    // Retrieve comments belonging to this review and map their IDs back
    // to the corresponding MongoDB findings.
    //
    // The createReview endpoint returns the review ID, not the IDs of every
    // inline comment, so fetch the review comments separately.
    // ---------------------------------------------------------------------------

    const githubComments = await octokit.paginate(
        octokit.rest.pulls.listReviewComments,
        {
            owner,
            repo,
            pull_number,
            per_page: 100,
        },
    );

    const commentsForReview = githubComments.filter(
        (comment) =>
            comment.pull_request_review_id === githubReviewId,
    );

    const usedCommentIds = new Set<number>();
    const findingCommentIds = new Map<number, number>();

    for (const expected of inlineComments) {
        const matchingComment = commentsForReview.find((comment) => {
            if (usedCommentIds.has(comment.id)) {
                return false;
            }

            return (
                comment.path === expected.path &&
                comment.line === expected.line &&
                comment.body === expected.body
            );
        });

        if (!matchingComment) {
            console.warn(`${logPrefix} Could not match GitHub comment`, {
                findingIndex: expected.findingIndex,
                file: expected.path,
                line: expected.line,
            });
            continue;
        }

        usedCommentIds.add(matchingComment.id);

        findingCommentIds.set(
            expected.findingIndex,
            matchingComment.id,
        );
    }

    // Save each returned GitHub comment ID on its corresponding finding.
    const fieldsToUpdate: Record<string, number> = {};

    for (const [findingIndex, commentId] of findingCommentIds) {
        fieldsToUpdate[`findings.${findingIndex}.githubCommentId`] =
            commentId;
    }

    if (Object.keys(fieldsToUpdate).length > 0) {
        const updatedReview = await Review.findByIdAndUpdate(
            mongoReviewId,
            {
                $set: fieldsToUpdate,
            },
            {
                returnDocument: "after",
            },
        );

        if (!updatedReview) {
            throw new Error(
                `GitHub comments were published, but their IDs could not be saved for review ${mongoReviewId.toString()}.`,
            );
        }
    }

    console.info(`${logPrefix} Publication completed`, {
        githubReviewId,
        githubReviewUrl,
        inlineCommentsPrepared: inlineComments.length,
        inlineCommentsSaved: findingCommentIds.size,
        findingsWithoutInlineComments: unanchoredFindings.length,
        reusedExistingReview,
    });

    return {
        githubReviewId,
        githubReviewUrl: githubReviewUrl ?? "",
        inlineCommentsSaved: findingCommentIds.size,
        findingsWithoutInlineComments: unanchoredFindings.length,
        reusedExistingReview,
    };
}
